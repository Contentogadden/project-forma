const line = (notes: number[], times = notes.map((_, i) => i), duration = 0.7): Score => ({
  events: notes.map((midi, i) => ({ midi, beat: times[i], duration })),
  beats: 8,
  stepBeats: 1,
});
const together = (...parts: Score[]): Score => ({
  events: parts.flatMap((p) => p.events),
  beats: 8,
  stepBeats: 1,
});
const chord = (notes: number[], beat: number, duration: number) =>
  notes.map((midi) => ({ midi, beat, duration, gain: 0.45 }));
