export function checkStudyAnswer(question: StudyQuestion, value: number[]) {
  const expected =
    question.kind === 'set' || question.kind === 'accents'
      ? [...question.answer].sort((a, b) => a - b)
      : question.answer;
  const actual =
    question.kind === 'set' || question.kind === 'accents'
      ? [...value].sort((a, b) => a - b)
      : value;
  const unique =
    (question.kind !== 'set' && question.kind !== 'accents') ||
    new Set(actual).size === actual.length;
  const ok =
    unique && actual.length === expected.length && actual.every((x, i) => x === expected[i]);
  return { ok, text: ok ? question.explanation : `Пока не совпало. ${question.hint}` };
}
export function answerScore(question: StudyQuestion, value: number[]): Score | undefined {
  if (question.kind === 'notes') {
    const note = value[0];
    if (!note || note < 0) return undefined;
    if (question.answerLayout === 'chord')
      return chord([...(question.answerPrefix ?? []), ...value.filter((v) => v > 0)]);
    if (question.answerBass !== undefined) {
      const line = [...(question.answerPrefix ?? []), ...value];
      return voices(
        line.map(() => question.answerBass!),
        line,
      );
    }
    if (question.answerPrefix)
      return melody([...question.answerPrefix, ...value.filter((v) => v > 0)]);
    if (question.id === 'motion-repair') return voices([60, 62], [67, note]);
    if (question.id === 'consonance-third') return voices([62], [note]);
    if (question.id === 'ornament-fill') return melody([60, note, 64]);
    if (question.id === 'mode-lydian') return melody([60, 62, 64, note, 67, 69, 71, 72]);
    if (question.id === 'interval-build' || question.id === 'function-resolve')
      return melody([question.given!.events[0].midi, note]);
    return melody(value.filter((v) => v > 0));
  }
  if (question.kind === 'set') return melody([...value].sort((a, b) => a - b).map((v) => 60 + v));
  if (question.kind === 'accents') {
    const step = question.pulseStep ?? 1;
    return {
      events: Array.from({ length: question.length ?? 6 }, (_, i) => ({
        midi: 60,
        beat: i * step,
        duration: 0.4 * step,
        gain: value.includes(i) ? 1 : 0.3,
      })),
      beats: (question.length ?? 6) * step,
      stepBeats: step,
    };
  }
  return question.options?.[value[0]]?.score;
}
