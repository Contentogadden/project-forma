export type StudyOption = { label: string; score?: Score };
export type StudyQuestion = {
  id: string;
  title: string;
  prompt: string;
  kind: 'choice' | 'notes' | 'accents' | 'set';
  options?: StudyOption[];
  answer: number[];
  explanation: string;
  hint: string;
  given?: Score;
  hideGiven?: boolean;
  answerLayout?: 'chord';
  answerPrefix?: number[];
  answerBass?: number;
  noteChoices?: number[];
  labels?: string[];
  length?: number;
  pulseStep?: number;
};
export type StudyLesson = {
  id: string;
  domain: string;
  topic: number;
  title: string;
  goal: string;
  theory: string[];
  rule: string;
  example: string;
  source: { title: string; url: string }[];
  questions: StudyQuestion[];
};
const source = (path: string, title: string) => ({
  title: `Open Music Theory · ${title}`,
  url: `https://openmusictheory.github.io/${path}.html`,
});
const choice = (
  id: string,
  title: string,
  prompt: string,
  labels: string[],
  correct: number,
  explanation: string,
  hint: string,
  given?: Score,
  scores?: Score[],
): StudyQuestion => ({
  id,
  title,
  prompt,
  kind: 'choice',
  options: labels.map((label, i) => ({ label, score: scores?.[i] })),
  answer: [correct],
  explanation,
  hint,
  given,
});
const notes = (
  id: string,
  title: string,
  prompt: string,
  answer: number[],
  explanation: string,
  hint: string,
  given?: Score,
): StudyQuestion => ({
  id,
  title,
  prompt,
  kind: 'notes',
  answer,
  noteChoices: Array.from({ length: 13 }, (_, i) => 60 + i),
  explanation,
  hint,
  given,
});
