const rhythm = (onsets: number[], beats: number, midi = 60): Score => ({
  events: onsets.map((beat) => ({ midi, beat, duration: 0.18 })),
  beats,
  stepBeats: 0.5,
});
const layers = (a: number[], b: number[], beats: number): Score => ({
  events: [
    ...a.map((beat) => ({ midi: 48, beat, duration: 0.2, gain: 0.7 })),
    ...b.map((beat) => ({ midi: 72, beat, duration: 0.2, gain: 0.7 })),
  ],
  beats,
  stepBeats: 0.5,
});
const progression = (chords: number[][]): Score => ({
  events: chords.flatMap((notes, i) =>
    notes.map((midi) => ({ midi, beat: i * 2, duration: 1.8, gain: 0.5 })),
  ),
  beats: chords.length * 2,
  stepBeats: 2,
});

