export function checkComposition(id: string, notes: number[]) {
  const task = compositionExercises[id];
  if (!fixed(task.initial, task.editable, notes))
    return { ok: false, text: 'Заданные ноты должны оставаться неизменными.' };
  const empty = task.editable.find((i) => !notes[i]);
  if (empty !== undefined)
    return { ok: false, text: `Заполните место ${empty + 1}: сейчас в нём пауза.` };
  const ok = task.accept(notes);
  const wrong = task.expected && task.editable.filter((i) => notes[i] !== task.expected![i]);
  if (wrong?.length)
    return {
      ok: false,
      text: `Сравните место ${wrong.map((i) => i + 1).join(', ')} с условием и образцом. Остальные заполненные ноты верны.`,
    };
  return { ok, text: ok ? task.success : `Пока не совпадает с условием. ${task.hint}` };
}
