const timed = (notes: number[], step: number): Score => melody(notes, step);
const shifted = (notes: number[], offset: number): Score => {
  const s = melody(notes);
  return {
    ...s,
    events: s.events.map((e) => ({ ...e, beat: e.beat + offset })),
    beats: s.beats + offset,
  };
};
