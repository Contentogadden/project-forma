    private Assignment task(
        String id,
        String title,
        String era,
        String composer,
        List<String> aspects,
        String level,
        int minutes,
        String prompt,
        String deliverable
    ) {
        var guide = AssignmentGuides.forId(id);
        return new Assignment(
            id,
            title,
            era,
            composer,
            aspects,
            level,
            minutes,
            prompt,
            deliverable,
            guide.material(),
            guide.steps(),
            guide.criteria(),
            guide.hint(),
            placement(id)
        );
    }

